import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {renderPreview} from '../make-preview.mjs';
import {ingestImage} from '../ingest-image.mjs';
import {makeZip} from '../zip.mjs';

test('offline export retains current visuals but excludes replaced/hidden user assets',async t=>{
 const folder=await fs.mkdtemp(path.join(os.tmpdir(),'slidebaby-assets-test-')),project=path.join(folder,'project');
 // All fixtures are generated by this test; never edit the installed studio.
 t.after(()=>fs.rm(folder,{recursive:true,force:true}));
 await fs.cp(fileURLToPath(new URL('../../',import.meta.url)),project,{recursive:true});
 async function asset(marker){const original=path.join(folder,marker+'.svg');await fs.writeFile(original,`<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><text y="40">${marker}</text></svg>`);return ingestImage({original,root:project});}
 const old=await asset('OLD-REPLACED-PRIVATE-FIXTURE'),current=await asset('CURRENT-PUBLIC-FIXTURE'),background=await asset('CURRENT-BACKGROUND-FIXTURE');
 const data=await fs.readFile(path.join(project,old.path)),oldPayload=data.toString('base64');
 async function save(slides){await fs.writeFile(path.join(project,'presentation.js'),'window.BRITE_PRESENTATION='+JSON.stringify({visualTemplate:{id:'brite',version:'1.0.0'},title:'Audit fixture',language:'en',slides})+';');}
 const cover={id:'cover',layout:'cover',template:{id:'cover-default',version:1},title:'Current heading',description:'Current description',image:current.path,imageAlt:'Current image',logo:old.path,chrome:{brand:{kind:'text',text:'Atlas'}}};
 await t.test('replacement and text-brand override remove the older payload',async()=>{
  await save([cover]);const html=await renderPreview(project,{exportEntry:null});
  const embedded=JSON.parse(html.match(/window\.BRITE_INLINE_ASSETS=(\{[^\n]*\});/)[1]);
  assert(Object.hasOwn(embedded,current.path));assert(!Object.hasOwn(embedded,old.path));assert(!html.includes(oldPayload));
  assert(html.includes('assets/images/cover-dark-photo.webp'));assert(html.includes('assets/figma/agenda-row-rule-dark.svg'));
 });
 await t.test('background, gallery and effective inherited image brand remain available',async()=>{
  await save([{...cover,background:{src:background.path,alt:'Background'},chrome:{brand:{kind:'image',src:old.path,alt:'Actual logo'}}},{id:'gallery',layout:'gallery',template:{id:'gallery-1',version:1},images:[{src:current.path,alt:'Photo'}]}]);
  const html=await renderPreview(project,{exportEntry:null});for(const image of [current,old,background])assert(html.includes(image.path));
 });
 await t.test('unused asset links are never followed; referenced links reject',async()=>{
  await save([cover]);const link='assets/user/unused-link.svg';await fs.symlink(path.join(folder,'OLD-REPLACED-PRIVATE-FIXTURE.svg'),path.join(project,link));
  assert(!(await renderPreview(project,{exportEntry:null})).includes(link));
  await save([{...cover,image:link}]);await assert.rejects(renderPreview(project,{exportEntry:null}),/symlink/);
 });
 await t.test('missing required media rejects rather than publishing a broken viewer',async()=>{
  await save([{...cover,image:'assets/user/missing.svg'}]);await assert.rejects(renderPreview(project,{exportEntry:null}),/ENOENT/);
 });
 await t.test('legacy renderer without dependency metadata still embeds Dark artwork',async()=>{
  await save([cover]);let engine=await fs.readFile(path.join(project,'engine.js'),'utf8');engine=engine.replace(',applyPalette,assetSources}',',applyPalette}');await fs.writeFile(path.join(project,'engine.js'),engine);
  const html=await renderPreview(project,{exportEntry:null});assert(html.includes('assets/figma/cover-brand-dark.svg'));assert(!html.includes(oldPayload));
 });
});

test('ZIP writer refuses ambiguous or escaping entry paths',()=>{
 for(const name of ['../private.txt','/absolute.txt','a/../../b','a\\b','C:/private','a//b','a\0b'])assert.throws(()=>makeZip([{name,bytes:Buffer.from('test')}]));
 assert.throws(()=>makeZip([{name:'same',bytes:Buffer.from('one')},{name:'same',bytes:Buffer.from('two')}]));
});
